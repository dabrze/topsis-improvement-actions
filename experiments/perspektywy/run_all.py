"""Run all Perspektywy experiments and write a reproducibility manifest."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from experiments.perspektywy import e1_walkthrough, e2_plan_vs_reality, e3_cross_method, e4_benchmark  # noqa: E402
from experiments.perspektywy.common import output_dirs  # noqa: E402
from experiments.perspektywy.config import FOCAL_UNIVERSITY, MAIN_YEAR  # noqa: E402


DESCRIPTIONS = {
    "e1_": "E1 walkthrough artifact.",
    "e2_": "E2 plan-survival artifact.",
    "e3_": "E3 cross-method artifact.",
    "e4_": "E4 benchmark artifact.",
}


def run(
    focal: str = FOCAL_UNIVERSITY,
    year: int = MAIN_YEAR,
    outdir: str | Path | None = None,
    *,
    quick: bool = False,
    e3_survival: bool = True,
    margins: bool = True,
    ablation: bool = True,
) -> None:
    dirs = output_dirs(outdir)
    e1_walkthrough.run(focal, year, outdir, quick=quick)
    e2_plan_vs_reality.run(
        focal,
        None,
        outdir,
        alphas=[0.0, 0.5] if quick and margins else ([0.0] if not margins else None),
        ablation=ablation,
    )
    e3_cross_method.run(focal, year, outdir, survival=e3_survival)
    e4_benchmark.run(focal, year, outdir, quick=quick)
    root = dirs["results"].parent
    artifacts = sorted(path for path in root.rglob("*") if path.is_file())
    lines = ["# Perspektywy experiment manifest", "", "Generated by `run_all.py`.", ""]
    for path in artifacts:
        if path.name == "MANIFEST.md":
            continue
        description = next(
            (text for prefix, text in DESCRIPTIONS.items() if path.name.startswith(prefix)),
            "Experiment support artifact.",
        )
        lines.append(f"- `{path.relative_to(root).as_posix()}` — {description}")
    (dirs["results"] / "MANIFEST.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--focal", default=FOCAL_UNIVERSITY)
    parser.add_argument("--year", type=int, default=MAIN_YEAR)
    parser.add_argument("--outdir", default=None)
    parser.add_argument("--quick", action="store_true", help="Use quick evolutionary settings, 20 regular E4 repetitions, and alpha values 0/0.5.")
    parser.add_argument("--skip-e3-survival", action="store_true", help="Skip E3 next-cycle survival analysis for development.")
    parser.add_argument("--skip-margins", action="store_true", help="Run only alpha-zero E2 plans.")
    parser.add_argument("--skip-ablation", action="store_true", help="Skip E2 values/weights ablation.")
    args = parser.parse_args()
    run(
        args.focal,
        args.year,
        args.outdir,
        quick=args.quick,
        e3_survival=not args.skip_e3_survival,
        margins=not args.skip_margins,
        ablation=not args.skip_ablation,
    )


if __name__ == "__main__":
    main()
